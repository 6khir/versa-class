function normalizeTptTaxonomyValue(value) {
  return String(value ?? '')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
    .replace(/\s+/g, ' ');
}

function canonicalTptTaxonomyValue(value, options) {
  const normalized = normalizeTptTaxonomyValue(value);
  if (!normalized) return '';
  return options.find((option) => normalizeTptTaxonomyValue(option) === normalized) || '';
}

function canonicalizeTptTaxonomyValues(values, options, limit) {
  const result = [];
  const seen = new Set();
  for (const value of Array.isArray(values) ? values : []) {
    const canonical = canonicalTptTaxonomyValue(value, options);
    const normalized = normalizeTptTaxonomyValue(canonical);
    if (!canonical || seen.has(normalized)) continue;
    result.push(canonical);
    seen.add(normalized);
    if (result.length >= limit) break;
  }
  return result;
}

function inspectTptListingTaxonomy(listing = {}) {
  const subjects = Array.isArray(listing.subjects) ? listing.subjects : [];
  const tags = Array.isArray(listing.tags) ? listing.tags : [];
  const invalidSubjects = subjects
    .map((value) => String(value ?? '').trim())
    .filter((value) => value && !canonicalTptTaxonomyValue(value, TPT_SUBJECT_AREA_OPTIONS));
  const invalidTags = tags
    .map((value) => String(value ?? '').trim())
    .filter((value) => value && !canonicalTptTaxonomyValue(value, TPT_TAG_OPTIONS));
  const validSubjects = canonicalizeTptTaxonomyValues(subjects, TPT_SUBJECT_AREA_OPTIONS, 3);
  const validTags = canonicalizeTptTaxonomyValues(tags, TPT_TAG_OPTIONS, 6);
  return {
    invalidSubjects,
    invalidTags,
    valid: invalidSubjects.length === 0
      && invalidTags.length === 0
      && validSubjects.length > 0
      && validTags.length > 0
  };
}

